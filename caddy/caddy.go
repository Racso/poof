package caddy

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"strings"

	"github.com/racso/poof/store"
)

// pausedResponse is served on every route of a paused project.
const pausedResponse = `respond "This site is temporarily unavailable." 503`

// GenerateCaddyfile builds a complete Caddyfile from the given projects and
// redirects. Only pass projects that are currently deployed (container running
// or static files present) — plus paused projects, which get a 503 route
// regardless of their deployment state.
// poofHost (e.g. "poof.example.com") and poofPort are used to add a route
// for the Poof API itself, which runs on the host rather than in a container.
func GenerateCaddyfile(projects []store.Project, redirects []store.Redirect, snippets map[string]string, poofHost string, poofPort int, staticDir string) string {
	var b strings.Builder

	// Warning header.
	fmt.Fprintf(&b, "# AUTO-GENERATED BY POOF — DO NOT EDIT\n")
	fmt.Fprintf(&b, "# Manual routes go in %s/*.Caddyfile\n\n", staticDir)

	// Global options: keep the admin API binding intact after every sync.
	fmt.Fprintf(&b, "{\n\tadmin 0.0.0.0:2019\n}\n\n")

	// Import manually-managed Caddyfile snippets.  The glob pattern means
	// an empty (or missing) directory is fine — Caddy won't error.
	fmt.Fprintf(&b, "import %s/*.Caddyfile\n\n", staticDir)

	// Poof's own API — runs as a container on poof-net, reachable by name.
	if poofHost != "" {
		fmt.Fprintf(&b, "%s {\n\treverse_proxy poof:%d\n}\n\n", poofHost, poofPort)
	}

	writeSnippet := func(name string) {
		if snip, ok := snippets[name]; ok && snip != "" {
			for _, line := range strings.Split(snip, "\n") {
				if line != "" {
					fmt.Fprintf(&b, "\t%s\n", line)
				}
			}
		}
	}

	for _, p := range projects {
		// Skip if the project's domain is already emitted as the poofHost block above.
		if poofHost != "" && p.Domain == poofHost {
			continue
		}

		// A paused project answers 503 on every route and its custom snippet
		// is withheld — nothing of the project's normal routing stays exposed.
		if p.Paused {
			fmt.Fprintf(&b, "%s {\n\t%s\n}\n\n", p.Domain, pausedResponse)
			continue
		}

		if p.IsStatic() {
			staticRoot := fmt.Sprintf("/var/lib/poof/static/%s/current", p.Name)
			fmt.Fprintf(&b, "%s {\n\troot * %s\n", p.Domain, staticRoot)
			if p.Static == "spa" {
				// The SPA fallback lives in a catch-all handle placed after the
				// custom snippet: a top-level try_files would run in Caddy's
				// rewrite phase, BEFORE any handle block in the snippet, and
				// rewrite e.g. /api/* to /index.html. Caddy evaluates handle
				// blocks in order of appearance (first match wins), so snippet
				// routes take precedence and everything else falls through here.
				writeSnippet(p.Name)
				fmt.Fprintf(&b, "\thandle {\n\t\ttry_files {path} /index.html\n\t\tfile_server\n\t}\n")
			} else {
				fmt.Fprintf(&b, "\tfile_server\n")
				writeSnippet(p.Name)
			}
		} else {
			fmt.Fprintf(&b, "%s {\n\treverse_proxy %s\n", p.Domain, p.Upstream())
			writeSnippet(p.Name)
		}
		fmt.Fprintf(&b, "}\n\n")
	}

	for _, r := range redirects {
		fmt.Fprintf(&b, "%s {\n\tredir https://%s{uri} 301\n}\n\n", r.FromDomain, r.ToDomain)
	}

	return b.String()
}

// ErrValidateUnavailable means the admin API could not be reached, so the
// config was neither accepted nor rejected — as opposed to Caddy answering
// that it is invalid. Callers should not treat it as a verdict: refusing to
// store a snippet because Caddy is down would block the very edit that fixes
// a host whose Caddy is down.
var ErrValidateUnavailable = errors.New("caddy admin API unreachable")

// Validate asks Caddy whether a Caddyfile is acceptable WITHOUT applying it,
// via the admin API's /adapt endpoint. Caddy validates and applies a config as
// a whole: one bad snippet makes it reject everything, which would leave live
// routing frozen at the last good config for every site on the host. Adapting
// first turns that into a plain error on the command that caused it.
func Validate(adminURL, caddyfile string) error {
	url := strings.TrimRight(adminURL, "/") + "/adapt"
	resp, err := http.Post(url, "text/caddyfile", bytes.NewBufferString(caddyfile))
	if err != nil {
		return fmt.Errorf("%w: %v", ErrValidateUnavailable, err)
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(resp.Body)
		return fmt.Errorf("caddy rejected the config: %s", adaptMessage(body, resp.Status))
	}
	return nil
}

// adaptMessage pulls the human-readable complaint out of Caddy's JSON error
// body ({"error": "..."}), falling back to the raw response.
func adaptMessage(body []byte, status string) string {
	var e struct {
		Error string `json:"error"`
	}
	if json.Unmarshal(body, &e) == nil && e.Error != "" {
		return e.Error
	}
	if t := strings.TrimSpace(string(body)); t != "" {
		return t
	}
	return status
}

// Reload posts the generated Caddyfile to the Caddy admin API for a
// zero-downtime config reload.
func Reload(adminURL, caddyfile string) error {
	url := strings.TrimRight(adminURL, "/") + "/load"
	resp, err := http.Post(url, "text/caddyfile", bytes.NewBufferString(caddyfile))
	if err != nil {
		return fmt.Errorf("caddy reload: %w", err)
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(resp.Body)
		return fmt.Errorf("caddy reload: status %d: %s", resp.StatusCode, strings.TrimSpace(string(body)))
	}
	return nil
}
