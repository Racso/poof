// Package workflow renders the GitHub Actions workflow Poof! wants in a
// project's repository. It only produces text: getting that text into the
// repository is the client's job (see cmd/ci_apply.go), and the server never
// holds a GitHub credential.
package workflow

import (
	"fmt"
	"strings"

	"github.com/racso/poof/defaults"
)

// CI mode strings. Kept aligned with store.CIMode* constants but redeclared
// here to avoid an import cycle (server depends on both packages).
const (
	CIModeManaged  = "managed"
	CIModeCallable = "callable"
)

// Spec is everything the workflow text depends on.
type Spec struct {
	ProjectName string
	PoofURL     string
	Branch      string
	Image       string // full image reference, tag ignored; "" derives from the repo
	Folder      string
	Static      string // "" | static | spa
	CIMode      string // managed (default) | callable
	Build       bool
}

// File is the path, relative to the repository root, of a project's
// Poof-managed workflow. The filename is the contract: any file at that path
// is considered Poof's and is overwritten on refresh or removed on disable.
func File(projectName string) string {
	return fmt.Sprintf(".github/workflows/poof-auto-ci-%s.yml", projectName)
}

// Workflow templates. The leading banner ("# [poof-auto-ci] …") is
// informational only: readers are warned not to edit the file, but nothing
// about it is verified by code.
//
// Placeholders replaced by Render:
//   POOF_TRIGGER_BLOCK → entire `on:` section, computed from ciMode
//                        (managed = push trigger; callable = workflow_call)
//   POOF_IMAGE_BASE    → Docker image base (without tag)
//   POOF_BUILD_ARGS    → docker build args ("." for root, "-f folder/Dockerfile folder" for subfolders)
//   POOF_PROJECT_NAME  → Poof! project name (may differ from GitHub repo name in monorepos)
//   POOF_PKG_NAME      → GHCR package name for cleanup
//   POOF_SERVER_URL    → this server's public URL (plain text; it is not a secret)
//   The deploy call authenticates with the job's GitHub OIDC token, so no
//   repo secret is needed.

// triggerBlock returns the YAML `on:` section for a workflow.
//
// For "managed" mode (the default), the workflow runs on push to the
// configured branch, optionally filtered by paths under `folder`, and can be
// dispatched by hand. A container workflow's dispatch takes an optional
// `tag`: an image already in the registry to redeploy without rebuilding. It
// is how an image that is no longer on the server gets pulled again, since
// the server has no registry credential of its own.
//
// For "callable" mode, the workflow exposes itself as a reusable workflow
// (`on: workflow_call`) so a user-owned outer workflow can `uses:` it after
// running its own steps (tests, lint, matrices, …). It also accepts
// `workflow_dispatch` so the deploy can still be fired manually from the
// GitHub Actions UI for debugging.
func triggerBlock(ciMode, branch, folder string, tagInput bool) string {
	if ciMode == CIModeCallable {
		// The secrets are no longer read (deploys authenticate with OIDC) but
		// stay declared, optional, so an outer workflow written for the old
		// shape that still passes them is not rejected by GitHub.
		return `on:
  workflow_call:
    secrets:
      POOF_URL:
        required: false
      POOF_TOKEN:
        required: false
  workflow_dispatch:
`
	}
	pathsBlock := ""
	if folder != "" {
		pathsBlock = fmt.Sprintf("    paths:\n      - \"%s/**\"\n", strings.TrimRight(folder, "/"))
	}
	dispatch := "  workflow_dispatch:\n"
	if tagInput {
		dispatch += `    inputs:
      tag:
        description: "Image tag already in the registry to redeploy (a commit sha). Empty builds this branch."
        required: false
`
	}
	return fmt.Sprintf("on:\n  push:\n    branches: [\"%s\"]\n%s%s", branch, pathsBlock, dispatch)
}

const containerTemplate = `# [poof-auto-ci] AUTO-GENERATED BY Poof! — CHANGES MAY BE OVERRIDDEN. DISABLE CI ON Poof! TO USE A CUSTOM FILE.
name: POOF_WORKFLOW_NAME

POOF_TRIGGER_BLOCK
permissions:
  contents: read
  packages: write
  id-token: write

jobs:
  deploy:
    if: vars.POOF_DISABLE != '1'
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6

      - name: Use an image already in the registry
        if: github.event_name == 'workflow_dispatch' && inputs.tag != ''
        run: echo "IMAGE=POOF_IMAGE_BASE:${{ inputs.tag }}" >> $GITHUB_ENV

      - name: Build and push image
        if: github.event_name != 'workflow_dispatch' || inputs.tag == ''
        run: |
          echo "${{ secrets.GITHUB_TOKEN }}" | docker login ghcr.io -u ${{ github.actor }} --password-stdin
          IMAGE=POOF_IMAGE_BASE:${{ github.sha }}
          TAGS=(-t "$IMAGE")
          LABELS=(--label co.racso.poof.managed=true
                  --label "org.opencontainers.image.revision=${{ github.sha }}"
                  --label "org.opencontainers.image.source=${{ github.server_url }}/${{ github.repository }}")
          # Branch builds only (not PRs or git tags): an immutable branch label, and a
          # moving :<branch> tag (docker/metadata-action convention) with characters
          # invalid in a tag replaced by '-', capped at the 128-char tag limit.
          if [[ "$GITHUB_REF" == refs/heads/* ]]; then
            BRANCH="${GITHUB_REF#refs/heads/}"
            BRANCH_TAG="${BRANCH//[^A-Za-z0-9_.-]/-}"
            BRANCH_IMAGE=POOF_IMAGE_BASE:${BRANCH_TAG:0:128}
            TAGS+=(-t "$BRANCH_IMAGE")
            LABELS+=(--label "co.racso.poof.branch=$BRANCH")
          fi
          docker build "${TAGS[@]}" "${LABELS[@]}" POOF_BUILD_ARGS
          docker push $IMAGE
          if [[ -n "${BRANCH_IMAGE:-}" ]]; then docker push "$BRANCH_IMAGE"; fi
          echo "IMAGE=$IMAGE" >> $GITHUB_ENV

      - name: Deploy via Poof!
        run: |
          # GitHub's OIDC token proves which repository is calling; the job's
          # own GITHUB_TOKEN lets Poof! pull the image and dies with the job.
          POOF_URL="POOF_SERVER_URL"
          JWT=$(curl -fsSL -H "Authorization: bearer $ACTIONS_ID_TOKEN_REQUEST_TOKEN" \
            "$ACTIONS_ID_TOKEN_REQUEST_URL&audience=$POOF_URL" | jq -r .value)
          curl -fsSL -X POST "$POOF_URL/projects/POOF_PROJECT_NAME/deploy" \
            -H "Authorization: Bearer $JWT" \
            -H "X-Poof-Registry-Token: ${{ secrets.GITHUB_TOKEN }}" \
            -H "Content-Type: application/json" \
            -d "{\"image\": \"${{ env.IMAGE }}\"}"

      - name: Clean up old images
        uses: actions/delete-package-versions@v5
        with:
          package-name: POOF_PKG_NAME
          package-type: container
          min-versions-to-keep: 3
          delete-only-untagged-versions: false
`

// staticDockerTemplate is used for static projects that have a Dockerfile.
// The Dockerfile builds the site; the output is extracted from /poof in the container.
// The container is never started (it only exists for `docker cp`), but `docker create`
// still requires a command when the image defines no CMD/ENTRYPOINT — which is the
// case for the recommended `FROM scratch` final stage — hence the explicit
// `noop-command` argument. It is never executed.
const staticDockerTemplate = `# [poof-auto-ci] AUTO-GENERATED BY Poof! — CHANGES MAY BE OVERRIDDEN. DISABLE CI ON Poof! TO USE A CUSTOM FILE.
name: POOF_WORKFLOW_NAME

POOF_TRIGGER_BLOCK
permissions:
  contents: read
  id-token: write

jobs:
  deploy:
    if: vars.POOF_DISABLE != '1'
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6

      - name: Build static site
        run: |
          docker build -t poof-build POOF_BUILD_ARGS
          docker create --name poof-extract poof-build noop-command
          docker cp poof-extract:/poof ./poof-output
          docker rm poof-extract

      - name: Deploy to Poof!
        run: |
          tar -czf site.tar.gz -C ./poof-output .
          POOF_URL="POOF_SERVER_URL"
          JWT=$(curl -fsSL -H "Authorization: bearer $ACTIONS_ID_TOKEN_REQUEST_TOKEN" \
            "$ACTIONS_ID_TOKEN_REQUEST_URL&audience=$POOF_URL" | jq -r .value)
          curl -fsSL -X POST "$POOF_URL/projects/POOF_PROJECT_NAME/deploy/static" \
            -H "Authorization: Bearer $JWT" \
            -H "Content-Type: application/gzip" \
            --data-binary @site.tar.gz
`

// staticDirectTemplate is used for static projects without a Dockerfile.
// The source directory is tarred and uploaded directly.
const staticDirectTemplate = `# [poof-auto-ci] AUTO-GENERATED BY Poof! — CHANGES MAY BE OVERRIDDEN. DISABLE CI ON Poof! TO USE A CUSTOM FILE.
name: POOF_WORKFLOW_NAME

POOF_TRIGGER_BLOCK
permissions:
  contents: read
  id-token: write

jobs:
  deploy:
    if: vars.POOF_DISABLE != '1'
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6

      - name: Deploy to Poof!
        run: |
          tar -czf /tmp/site.tar.gz --exclude=.git -C POOF_FOLDER .
          POOF_URL="POOF_SERVER_URL"
          JWT=$(curl -fsSL -H "Authorization: bearer $ACTIONS_ID_TOKEN_REQUEST_TOKEN" \
            "$ACTIONS_ID_TOKEN_REQUEST_URL&audience=$POOF_URL" | jq -r .value)
          curl -fsSL -X POST "$POOF_URL/projects/POOF_PROJECT_NAME/deploy/static" \
            -H "Authorization: Bearer $JWT" \
            -H "Content-Type: application/gzip" \
            --data-binary @/tmp/site.tar.gz
`

// imageBase strips any tag from image and returns the bare image reference.
func imageBase(image string) string {
	return strings.SplitN(image, ":", 2)[0]
}

// imagePackageName extracts the GHCR package name from an image reference.
// For "ghcr.io/owner/pkg" it returns "pkg"; for "ghcr.io/owner/sub/pkg" it
// returns "sub/pkg". Falls back to the last path component for other formats.
func imagePackageName(image string) string {
	base := imageBase(image)
	parts := strings.SplitN(base, "/", 3)
	if len(parts) == 3 {
		return parts[2]
	}
	if idx := strings.LastIndex(base, "/"); idx >= 0 {
		return base[idx+1:]
	}
	return base
}

// Render returns the workflow text for spec. It is deterministic: the same
// spec always renders byte-identical text, which is what lets a client skip
// a commit when the file in the repository already matches.
func Render(spec Spec) string {
	isStatic := spec.Static == "static" || spec.Static == "spa"
	isCallable := spec.CIMode == CIModeCallable

	// folder support: build args (path filter goes through triggerBlock)
	buildArgs := "."
	cleanFolder := spec.Folder
	if spec.Folder != "" {
		cleanFolder = strings.TrimRight(spec.Folder, "/")
		buildArgs = fmt.Sprintf("-f %s/Dockerfile %s", cleanFolder, cleanFolder)
	}

	// Build human-readable workflow name.
	workflowName := "Poof! deploy"
	var qualifiers []string
	if isStatic {
		qualifiers = append(qualifiers, "static")
	}
	if cleanFolder != "" {
		qualifiers = append(qualifiers, cleanFolder)
	}
	if spec.Branch != defaults.Branch && !isCallable {
		qualifiers = append(qualifiers, spec.Branch)
	}
	if isCallable {
		qualifiers = append(qualifiers, "callable")
	}
	if len(qualifiers) > 0 {
		workflowName += " (" + strings.Join(qualifiers, ", ") + ")"
	}

	var text string
	if isStatic {
		if spec.Build {
			text = staticDockerTemplate
			text = strings.ReplaceAll(text, "POOF_BUILD_ARGS", buildArgs)
		} else {
			text = staticDirectTemplate
			uploadFolder := "."
			if cleanFolder != "" {
				uploadFolder = cleanFolder
			}
			text = strings.ReplaceAll(text, "POOF_FOLDER", uploadFolder)
		}
	} else {
		imgBase := `ghcr.io/$(echo "${{ github.repository }}" | tr '[:upper:]' '[:lower:]')`
		pkgName := `${{ github.event.repository.name }}`
		if spec.Image != "" {
			imgBase = imageBase(spec.Image)
			pkgName = imagePackageName(spec.Image)
		}
		text = containerTemplate
		text = strings.ReplaceAll(text, "POOF_IMAGE_BASE", imgBase)
		text = strings.ReplaceAll(text, "POOF_BUILD_ARGS", buildArgs)
		text = strings.ReplaceAll(text, "POOF_PKG_NAME", pkgName)
	}

	text = strings.ReplaceAll(text, "POOF_WORKFLOW_NAME", workflowName)
	text = strings.ReplaceAll(text, "POOF_TRIGGER_BLOCK", triggerBlock(spec.CIMode, spec.Branch, cleanFolder, !isStatic))
	text = strings.ReplaceAll(text, "POOF_PROJECT_NAME", spec.ProjectName)
	text = strings.ReplaceAll(text, "POOF_SERVER_URL", strings.TrimRight(spec.PoofURL, "/"))
	return text
}
